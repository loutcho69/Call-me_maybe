"""Constraints: which tokens may come next while writing one value.

Each constraint is a small state machine. It answers three questions:

* ``allows(data)``: would these token bytes keep the value valid?
* ``advance(data)``: accept these bytes and update the state.
* ``mask(index)``: boolean array over the whole vocabulary, True for
  every token the model is allowed to pick now.

The JSON structure around the values (``{"name": "``, ``", "a": `` ...)
is never generated by the model: the generator writes it itself.
"""

import json

import numpy as np
import numpy.typing as npt
from pydantic import BaseModel, ConfigDict, Field

from src.models import ArgValue
from src.vocab import Vocabulary

BoolArray = npt.NDArray[np.bool_]

DIGITS = b"0123456789"
# Octets qui terminent une valeur non-chaine (nombre, booleen).
TERMINATORS = b",} \n\r\t"
# Lettres autorisees apres un antislash dans une chaine JSON.
# \u est volontairement exclu : le modele ecrit les accents directement.
ESCAPABLE = b'"\\/bfnrt'
NUMERIC = b"0123456789.-"
QUOTE = ord('"')
BACKSLASH = ord("\\")
SPACE = ord(" ")


class TokenIndex(BaseModel):
    """Per-token facts computed once, used to build masks quickly.

    Attributes:
        token_bytes: Bytes written by each token id (``b""`` = forbidden).
        by_bytes: Reverse lookup, bytes -> token id.
        lengths: Number of bytes of each token.
        plain_text: Tokens safe anywhere inside a JSON string (no quote,
            no backslash, no control character).
        ends_value: Tokens whose first byte ends a number or boolean.
        numeric_ids: Tokens made only of digits, ``.`` and ``-``.
        space_numeric_ids: A space followed by numeric characters
            (``" -"``, ``" "``): how a value naturally starts after ``:``.
        string_tricky_ids: Tokens containing a quote or a backslash.
        escape_start_ids: Tokens that may follow a backslash.
    """

    model_config = ConfigDict(arbitrary_types_allowed=True, frozen=True)

    token_bytes: list[bytes]
    by_bytes: dict[bytes, int]
    lengths: npt.NDArray[np.int64]
    plain_text: BoolArray
    ends_value: BoolArray
    numeric_ids: list[int]
    space_numeric_ids: list[int]
    string_tricky_ids: list[int]
    escape_start_ids: list[int]

    @property
    def size(self) -> int:
        """Number of token ids."""
        return len(self.token_bytes)

    @classmethod
    def build(cls, vocab: Vocabulary) -> "TokenIndex":
        """Scan the vocabulary once and precompute every category.

        Args:
            vocab: The decoded vocabulary.

        Returns:
            The index.
        """
        size = vocab.size
        by_bytes: dict[bytes, int] = {}
        lengths = np.zeros(size, dtype=np.int64)
        plain_text = np.zeros(size, dtype=np.bool_)
        ends_value = np.zeros(size, dtype=np.bool_)
        numeric_ids: list[int] = []
        space_numeric_ids: list[int] = []
        tricky_ids: list[int] = []
        escape_ids: list[int] = []
        for token_id, data in enumerate(vocab.token_bytes):
            if not data:
                continue
            by_bytes.setdefault(data, token_id)
            lengths[token_id] = len(data)
            has_quote = QUOTE in data or BACKSLASH in data
            if has_quote:
                tricky_ids.append(token_id)
            elif min(data) >= 0x20:
                plain_text[token_id] = True
            if data[0] in TERMINATORS:
                ends_value[token_id] = True
            if data[0] in ESCAPABLE:
                escape_ids.append(token_id)
            if all(byte in NUMERIC for byte in data):
                numeric_ids.append(token_id)
            elif data[0] == SPACE and all(b in NUMERIC for b in data[1:]):
                space_numeric_ids.append(token_id)
        return cls(
            token_bytes=vocab.token_bytes,
            by_bytes=by_bytes,
            lengths=lengths,
            plain_text=plain_text,
            ends_value=ends_value,
            numeric_ids=numeric_ids,
            space_numeric_ids=space_numeric_ids,
            string_tricky_ids=tricky_ids,
            escape_start_ids=escape_ids,
        )

    def empty_mask(self) -> BoolArray:
        """Return an all-False mask of the vocabulary size."""
        return np.zeros(self.size, dtype=np.bool_)


def _tail_is_closing(tail: bytes) -> bool:
    """Tell whether bytes after the end of a value are acceptable.

    Args:
        tail: Bytes of the token after the value ended.

    Returns:
        True if they only contain separators like ``,`` or ``}``.
    """
    return all(byte in TERMINATORS for byte in tail)


class Constraint(BaseModel):
    """Common interface of every constraint.

    Attributes:
        done: True once the value is complete.
    """

    done: bool = False

    def allows(self, data: bytes) -> bool:
        """Tell whether a token with these bytes may come next.

        Args:
            data: Bytes of the candidate token.

        Returns:
            True if the value stays valid.
        """
        raise NotImplementedError

    def advance(self, data: bytes) -> None:
        """Accept a token (must be allowed) and update the state.

        Args:
            data: Bytes of the chosen token.
        """
        raise NotImplementedError

    def mask(self, index: TokenIndex) -> BoolArray:
        """Compute the allowed tokens for the current state.

        Args:
            index: Precomputed token facts.

        Returns:
            Boolean array, True for allowed token ids.
        """
        raise NotImplementedError

    def forced_completion(self) -> bytes | None:
        """Bytes that can be written without asking the model, if any.

        Returns:
            The only possible continuation, or None if there is a choice.
        """
        return None

    def value(self) -> ArgValue:
        """Return the finished value as a Python object."""
        raise NotImplementedError

    def _check(self, index: TokenIndex, ids: list[int]) -> BoolArray:
        """Build a mask by testing a list of candidate ids one by one.

        Args:
            index: Precomputed token facts.
            ids: Candidate token ids.

        Returns:
            Mask with True for the candidates that are allowed.
        """
        result = index.empty_mask()
        for token_id in ids:
            if self.allows(index.token_bytes[token_id]):
                result[token_id] = True
        return result


class NameConstraint(Constraint):
    """The function name: must become exactly one of the known names.

    Attributes:
        names: Allowed names, as bytes.
        content: Bytes written so far.
    """

    names: list[bytes] = Field(min_length=1)
    content: bytes = b""

    def _compatible(self) -> list[bytes]:
        """Return the names that still start with the content."""
        return [name for name in self.names if name.startswith(self.content)]

    def _scan(self, data: bytes) -> tuple[bytes, bool] | None:
        """Apply bytes to the content without changing the state.

        Returns:
            (new content, finished) or None if not allowed.
        """
        if not data:
            return None
        if QUOTE in data:
            cut = data.index(QUOTE)
            head = self.content + data[:cut]
            if head in self.names and _tail_is_closing(data[cut + 1:]):
                return head, True
            return None
        new = self.content + data
        if any(name.startswith(new) for name in self.names):
            return new, False
        return None

    def allows(self, data: bytes) -> bool:
        """See Constraint.allows."""
        return self._scan(data) is not None

    def advance(self, data: bytes) -> None:
        """See Constraint.advance."""
        result = self._scan(data)
        if result is None:
            raise ValueError(f"token {data!r} not allowed in a name")
        self.content, self.done = result
        # Nom complet et aucun autre nom plus long : c'est fini.
        if self._compatible() == [self.content]:
            self.done = True

    def forced_completion(self) -> bytes | None:
        """Only one name left: the rest can be written directly."""
        compatible = self._compatible()
        if len(compatible) == 1:
            return compatible[0][len(self.content):]
        return None

    def mask(self, index: TokenIndex) -> BoolArray:
        """Allow tokens equal to a prefix of a remaining name part."""
        result = index.empty_mask()
        for name in self._compatible():
            rest = name[len(self.content):]
            for end in range(1, len(rest) + 1):
                token_id = index.by_bytes.get(rest[:end])
                if token_id is not None:
                    result[token_id] = True
        if self.content in self.names:
            # Nom complet mais ambigu : le modele peut fermer le guillemet.
            result |= self._check(index, index.string_tricky_ids)
        return result

    def value(self) -> str:
        """Return the chosen name."""
        return self.content.decode("utf-8")


class NumberConstraint(Constraint):
    """A JSON number (or integer): `` ?-?digits(.digits)?``.

    The value is written right after ``:``, so one leading space is
    accepted: the model can then use its natural tokens such as ``" -"``.

    Attributes:
        integer: True for the ``integer`` type (no decimal point).
        max_length: Maximum number of characters.
        text: Characters written so far (without the leading space).
        spaced: True once the optional leading space was written.
    """

    integer: bool = False
    max_length: int = 40
    text: str = ""
    spaced: bool = False

    def _complete(self, text: str) -> bool:
        """A number needs at least one digit."""
        return any(char.isdigit() for char in text)

    def _scan(self, data: bytes) -> tuple[str, bool, bool] | None:
        """Apply bytes to the text without changing the state.

        Returns:
            (new text, spaced, finished) or None if not allowed.
        """
        if not data:
            return None
        text, spaced = self.text, self.spaced
        for byte in data:
            if byte == SPACE and not text and not spaced:
                spaced = True
                continue
            if byte in TERMINATORS:
                return (text, spaced, True) if self._complete(text) else None
            char = chr(byte)
            if byte in DIGITS:
                text += char
            elif char == "-" and not text:
                text += char
            elif (char == "." and not self.integer and "." not in text
                  and self._complete(text)):
                text += char
            else:
                return None
            if len(text) > self.max_length:
                return None
        return text, spaced, False

    def allows(self, data: bytes) -> bool:
        """See Constraint.allows."""
        return self._scan(data) is not None

    def advance(self, data: bytes) -> None:
        """See Constraint.advance."""
        result = self._scan(data)
        if result is None:
            raise ValueError(f"token {data!r} not allowed in a number")
        self.text, self.spaced, self.done = result

    def mask(self, index: TokenIndex) -> BoolArray:
        """Digits that fit, plus any terminator once a digit exists."""
        candidates = index.numeric_ids
        if not self.text and not self.spaced:
            candidates = candidates + index.space_numeric_ids
        result = self._check(index, candidates)
        if self._complete(self.text):
            result |= index.ends_value
        return result

    def value(self) -> ArgValue:
        """Return an int or a float (``2`` -> ``2.0`` for numbers)."""
        if self.integer:
            return int(self.text)
        return float(self.text)


class StringConstraint(Constraint):
    """A JSON string, written right after ``:``.

    The model writes an optional space and the opening quote itself, so
    it can use its natural tokens (``" \\"*"`` is one Qwen token).
    ``content`` holds the JSON-escaped bytes between the quotes
    (``\\"`` stays two bytes); ``value()`` decodes them with json.

    Attributes:
        max_bytes: Maximum length of the escaped content.
        content: Escaped bytes written so far.
        escape: True right after a backslash.
        opened: True once the opening quote was written.
        spaced: True once the optional leading space was written.
    """

    max_bytes: int = 200
    content: bytes = b""
    escape: bool = False
    opened: bool = False
    spaced: bool = False

    def _scan(
        self, data: bytes
    ) -> tuple[bytes, bool, bool, bool, bool] | None:
        """Apply bytes without changing the state.

        Returns:
            (content, escape, opened, spaced, finished) or None.
        """
        if not data:
            return None
        content, escape = self.content, self.escape
        opened, spaced = self.opened, self.spaced
        for position, byte in enumerate(data):
            if not opened:
                if byte == SPACE and not spaced:
                    spaced = True
                elif byte == QUOTE:
                    opened = True
                else:
                    return None
            elif escape:
                if byte not in ESCAPABLE:
                    return None
                content += bytes([byte])
                escape = False
            elif byte == QUOTE:
                if not _tail_is_closing(data[position + 1:]):
                    return None
                return content, False, True, spaced, True
            elif byte == BACKSLASH:
                # Il faut la place pour l'antislash et la lettre qui suit.
                if len(content) + 2 > self.max_bytes:
                    return None
                content += b"\\"
                escape = True
            elif byte < 0x20:
                return None
            else:
                content += bytes([byte])
            if len(content) > self.max_bytes:
                return None
        return content, escape, opened, spaced, False

    def allows(self, data: bytes) -> bool:
        """See Constraint.allows."""
        return self._scan(data) is not None

    def advance(self, data: bytes) -> None:
        """See Constraint.advance."""
        result = self._scan(data)
        if result is None:
            raise ValueError(f"token {data!r} not allowed in a string")
        (self.content, self.escape, self.opened, self.spaced,
         self.done) = result

    def mask(self, index: TokenIndex) -> BoolArray:
        """Plain text that fits, plus checked quote/backslash tokens."""
        if not self.opened:
            # Avant le guillemet : seuls " ou un espace peuvent venir.
            result = self._check(index, index.string_tricky_ids)
            space_id = index.by_bytes.get(b" ")
            if space_id is not None and not self.spaced:
                result[space_id] = True
            return result
        if self.escape:
            return self._check(index, index.escape_start_ids)
        room = self.max_bytes - len(self.content)
        result = index.plain_text & (index.lengths <= room)
        result |= self._check(index, index.string_tricky_ids)
        return result

    def value(self) -> str:
        """Decode the escaped content into the real string."""
        content = self.content
        if self.escape:
            content = content[:-1]  # antislash orphelin si on a coupe
        # 'ignore' retire un eventuel demi-caractere coupe par la limite.
        text = content.decode("utf-8", errors="ignore")
        decoded = json.loads('"' + text + '"')
        return str(decoded)


class BooleanConstraint(Constraint):
    """``true`` or ``false``, with one optional leading space.

    Attributes:
        content: Bytes of the word written so far.
        spaced: True once the optional leading space was written.
    """

    content: bytes = b""
    spaced: bool = False

    def _scan(self, data: bytes) -> tuple[bytes, bool, bool] | None:
        """Apply bytes without changing the state.

        Returns:
            (new content, spaced, finished) or None.
        """
        if not data:
            return None
        spaced = self.spaced
        if not self.content and not spaced and data[0] == SPACE:
            spaced, data = True, data[1:]
            if not data:
                return b"", True, False
        new = self.content + data
        for word in (b"true", b"false"):
            if word.startswith(new):
                return new, spaced, new == word
            if new.startswith(word) and _tail_is_closing(new[len(word):]):
                return word, spaced, True
        return None

    def allows(self, data: bytes) -> bool:
        """See Constraint.allows."""
        return self._scan(data) is not None

    def advance(self, data: bytes) -> None:
        """See Constraint.advance."""
        result = self._scan(data)
        if result is None:
            raise ValueError(f"token {data!r} not allowed in a boolean")
        self.content, self.spaced, self.done = result

    def mask(self, index: TokenIndex) -> BoolArray:
        """Tokens equal to a prefix of the rest of true / false."""
        result = index.empty_mask()
        starts = [b""]
        if not self.content and not self.spaced:
            starts.append(b" ")  # " true" est un seul token chez Qwen
        for word in (b"true", b"false"):
            if not word.startswith(self.content):
                continue
            rest = word[len(self.content):]
            for start in starts:
                # Avec l'espace devant, le token " " seul compte aussi.
                first = 0 if start else 1
                for end in range(first, len(rest) + 1):
                    token_id = index.by_bytes.get(start + rest[:end])
                    if token_id is not None:
                        result[token_id] = True
        return result

    def value(self) -> bool:
        """Return the boolean."""
        return self.content == b"true"


def make_value_constraint(param_type: str) -> Constraint:
    """Create the constraint matching a parameter type.

    Args:
        param_type: Normalized JSON type from the function definition.

    Returns:
        A fresh constraint in its initial state.

    Raises:
        ValueError: If the type cannot be generated.
    """
    if param_type == "number":
        return NumberConstraint()
    if param_type == "integer":
        return NumberConstraint(integer=True)
    if param_type == "boolean":
        return BooleanConstraint()
    if param_type == "string":
        return StringConstraint()
    raise ValueError(f"unsupported parameter type {param_type!r}")
